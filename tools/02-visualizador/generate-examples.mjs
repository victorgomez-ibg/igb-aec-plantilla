// Pre-generates the three "modo respaldo" examples with the real APIs and embeds them
// (plan JSON + compressed JPEG render as base64) in respaldo.js.
// Usage (repo root):
//   ANTHROPIC_API_KEY=… GEMINI_API_KEY=… node tools/02-visualizador/generate-examples.mjs [indices…]
// Requires macOS `sips` to compress the renders.
import { readFileSync, writeFileSync, existsSync, mkdtempSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const { ANTHROPIC_API_KEY, GEMINI_API_KEY } = process.env;
if (!ANTHROPIC_API_KEY || !GEMINI_API_KEY) { console.error('Set ANTHROPIC_API_KEY and GEMINI_API_KEY'); process.exit(1); }
const mem = new Map([['igb-aec.anthropic_key', ANTHROPIC_API_KEY], ['igb-aec.gemini_key', GEMINI_API_KEY]]);
globalThis.localStorage = { getItem: (k) => mem.get(k) ?? null, setItem: (k, v) => mem.set(k, v), removeItem: (k) => mem.delete(k) };

const { generateJSON } = await import('../../shared/js/claude-client.js');
const { generateImage } = await import('../../shared/js/gemini-client.js');
const { SCHEMA, SYSTEM, buildPrompt, buildRenderPrompt, EJEMPLOS_TEXTO } = await import('./prompt.js');
const { dibujarPlano } = await import('./plan-svg.js');

const OUT = new URL('./respaldo.js', import.meta.url);
const tmp = mkdtempSync(join(tmpdir(), 'viz-'));
const prev = existsSync(OUT) ? (await import(OUT.href + '?t=' + Date.now())).EJEMPLOS : [];
const only = process.argv.slice(2).map(Number).filter(Number.isInteger);

async function one(i, intento = 1) {
  const r = await gen(i);
  if (r._avisos.length && intento < 3) { console.log(`[${i}] retry (avisos)`); return one(i, intento + 1); }
  delete r._avisos;
  return r;
}

async function gen(i) {
  const descripcion = EJEMPLOS_TEXTO[i];
  const t0 = Date.now();
  const [plan, img] = await Promise.all([
    generateJSON({ system: SYSTEM, prompt: buildPrompt(descripcion), schema: SCHEMA, effort: process.env.EFFORT || 'low', maxTokens: 16000 })
      .then((r) => ({ ...r, s: (Date.now() - t0) / 1000 })),
    generateImage({ prompt: buildRenderPrompt(descripcion) }).then((r) => ({ ...r, s: (Date.now() - t0) / 1000 })),
  ]);
  const src = join(tmp, `r${i}.${img.mimeType.includes('png') ? 'png' : 'jpg'}`);
  const dst = join(tmp, `r${i}-c.jpg`);
  writeFileSync(src, Buffer.from(img.base64, 'base64'));
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '72', '-Z', '1280', src, '--out', dst], { stdio: 'ignore' });
  const jpg = readFileSync(dst).toString('base64');
  const d = dibujarPlano(plan.data);
  console.log(`[${i}] claude=${plan.s.toFixed(1)}s (${plan.model}, out=${plan.usage.output_tokens}) gemini=${img.s.toFixed(1)}s (${img.model}) jpg=${Math.round(jpg.length * 0.75 / 1024)}KB area=${d.areaTotal} avisos=${JSON.stringify(d.avisos)}`);
  writeFileSync(new URL(`./ejemplo-${i}.svg`, `file://${tmp}/`), d.svg);
  return { _avisos: d.avisos, descripcion, plano: plan.data, render: { mimeType: 'image/jpeg', base64: jpg }, generado: new Date().toISOString(), modelos: { plano: plan.model, render: img.model } };
}

const idx = only.length ? only : EJEMPLOS_TEXTO.map((_, i) => i);
const results = await Promise.allSettled(idx.map(one));
const EJ = EJEMPLOS_TEXTO.map((_, i) => prev[i] || null);
results.forEach((r, k) => {
  if (r.status === 'fulfilled') EJ[idx[k]] = r.value;
  else console.error(`[${idx[k]}] FAILED:`, r.reason?.message || r.reason);
});
writeFileSync(OUT, `// Generated by generate-examples.mjs — real API output, embedded for "modo respaldo". Do not edit by hand.\nexport const EJEMPLOS = ${JSON.stringify(EJ)};\n`);
console.log(`wrote respaldo.js (${Math.round(readFileSync(OUT).length / 1024)} KB), svgs in ${tmp}`);
